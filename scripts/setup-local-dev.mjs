#!/usr/bin/env node
/**
 * Setup script for local development with @openzeppelin/ui-* packages
 *
 * This script configures a consuming project to use local versions of the
 * UI Kit packages from a sibling openzeppelin-ui checkout.
 *
 * Usage:
 *   # From your project directory (assuming openzeppelin-ui is a sibling):
 *   node ../openzeppelin-ui/scripts/setup-local-dev.mjs
 *
 *   # Or with a custom path:
 *   node /path/to/openzeppelin-ui/scripts/setup-local-dev.mjs --ui-path ../my-ui-fork
 *
 * What this script does:
 *   1. Creates/updates .pnpmfile.cjs with the local resolution hook
 *   2. Adds dev:local and dev:npm convenience scripts to package.json
 *   3. Prints next steps for the developer
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Parse arguments
const args = process.argv.slice(2);
const uiPathIndex = args.indexOf('--ui-path');
const customUiPath = uiPathIndex !== -1 ? args[uiPathIndex + 1] : null;

// Determine the relative path from CWD to openzeppelin-ui
const cwd = process.cwd();
const uiRepoRoot = path.resolve(__dirname, '..');
const defaultRelativePath = path.relative(cwd, uiRepoRoot) || '.';
const uiPath = customUiPath || defaultRelativePath;

console.log('\n🔧 Setting up local development for @openzeppelin/ui-* packages\n');
console.log(`   Project directory: ${cwd}`);
console.log(`   UI Kit path: ${uiPath}\n`);

// ============================================================================
// 1. Create/update .pnpmfile.cjs
// ============================================================================

const pnpmfileContent = `/**
 * pnpm hook for local development with @openzeppelin/ui-* packages
 *
 * This file enables seamless local development by dynamically resolving
 * @openzeppelin/ui-* packages to local file paths when LOCAL_UI=true.
 *
 * Usage:
 *   LOCAL_UI=true pnpm install   # Use local packages
 *   pnpm install                  # Use npm packages (default)
 *
 * Or use the convenience scripts:
 *   pnpm dev:local               # Enable local packages
 *   pnpm dev:npm                 # Switch to npm packages
 *
 * Generated by: openzeppelin-ui/scripts/setup-local-dev.mjs
 */

const path = require('path');

const LOCAL_UI_PATH = process.env.LOCAL_UI_PATH || '${uiPath}';

/**
 * Maps npm package names to their directory paths within openzeppelin-ui
 */
const UI_PACKAGE_MAP = {
  '@openzeppelin/ui-types': 'packages/types',
  '@openzeppelin/ui-utils': 'packages/utils',
  '@openzeppelin/ui-styles': 'packages/styles',
  '@openzeppelin/ui-components': 'packages/components',
  '@openzeppelin/ui-renderer': 'packages/renderer',
  '@openzeppelin/ui-react': 'packages/react',
  '@openzeppelin/ui-storage': 'packages/storage',
};

/**
 * Hook called by pnpm for each package being resolved
 * @param {object} pkg - The package.json content
 * @param {object} context - Context with directory info and logging
 * @returns {object} - Modified package.json content
 */
function readPackage(pkg, context) {
  // Skip if local development is not enabled
  if (process.env.LOCAL_UI !== 'true') {
    return pkg;
  }

  // Replace @openzeppelin/ui-* dependencies with local file: references
  for (const depType of ['dependencies', 'devDependencies', 'peerDependencies']) {
    if (!pkg[depType]) continue;

    for (const [npmName, localPath] of Object.entries(UI_PACKAGE_MAP)) {
      if (pkg[depType][npmName]) {
        const absolutePath = path.resolve(context.dir, LOCAL_UI_PATH, localPath);
        pkg[depType][npmName] = \`file:\${absolutePath}\`;
        context.log(\`[local-dev] \${npmName} → \${absolutePath}\`);
      }
    }
  }

  return pkg;
}

module.exports = {
  hooks: {
    readPackage,
  },
};
`;

const pnpmfilePath = path.join(cwd, '.pnpmfile.cjs');
const pnpmfileExists = fs.existsSync(pnpmfilePath);

if (pnpmfileExists) {
  const existingContent = fs.readFileSync(pnpmfilePath, 'utf-8');
  if (existingContent.includes('UI_PACKAGE_MAP')) {
    console.log('⏭️  .pnpmfile.cjs already configured for UI Kit local development');
  } else {
    console.log('⚠️  .pnpmfile.cjs exists but does not contain UI Kit hooks.');
    console.log('   Please manually merge the following into your existing file:\n');
    console.log('   ' + pnpmfilePath);
    console.log('\n   Or backup and replace with: --force flag (not implemented)\n');
  }
} else {
  fs.writeFileSync(pnpmfilePath, pnpmfileContent);
  console.log('✅ Created .pnpmfile.cjs');
}

// ============================================================================
// 2. Update package.json with convenience scripts
// ============================================================================

const packageJsonPath = path.join(cwd, 'package.json');

if (!fs.existsSync(packageJsonPath)) {
  console.log('⚠️  No package.json found in current directory');
  process.exit(1);
}

const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf-8'));

if (!packageJson.scripts) {
  packageJson.scripts = {};
}

const scriptsToAdd = {
  'dev:local':
    "LOCAL_UI=true pnpm install --force && echo '✅ Using local @openzeppelin/ui-* packages'",
  'dev:npm': "pnpm install --force && echo '✅ Using npm @openzeppelin/ui-* packages'",
};

let scriptsAdded = false;
for (const [name, command] of Object.entries(scriptsToAdd)) {
  if (!packageJson.scripts[name]) {
    packageJson.scripts[name] = command;
    scriptsAdded = true;
    console.log(`✅ Added script: ${name}`);
  } else {
    console.log(`⏭️  Script already exists: ${name}`);
  }
}

if (scriptsAdded) {
  fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 2) + '\n');
  console.log('✅ Updated package.json');
}

// ============================================================================
// 3. Print next steps
// ============================================================================

console.log(`
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Setup complete! Next steps:

1. Ensure the UI Kit is built:
   cd ${uiPath} && pnpm install && pnpm build

2. Enable local packages in this project:
   pnpm dev:local

3. Start development as usual:
   pnpm dev

To switch back to npm packages:
   pnpm dev:npm

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
`);
